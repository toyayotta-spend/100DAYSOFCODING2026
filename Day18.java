public class Day18 {
    public static void main(String[] args) {

        // Konversi Otomatis
        // Dari tipe data kecil ke tipe data besar

        int angkaInt = 100;

        // int dikonversi otomatis menjadi long
        long angkaLong = angkaInt;

        // long dikonversi otomatis menjadi float
        float angkaFloat = angkaLong;

        // Menampilkan hasil
        System.out.println("Nilai int   = " + angkaInt);
        System.out.println("Nilai long  = " + angkaLong);
        System.out.println("Nilai float = " + angkaFloat);
    }
}
