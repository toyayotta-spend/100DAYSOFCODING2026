public class Day5 {
    public static void main(String[] args) {

        double tinggiBadan = 165.5;
        float beratBadan = 55.5f;

        System.out.println(
            "Nilai dari tipe data double adalah: " + tinggiBadan);
        System.out.println(
            "Nilai dari tipe data float adalah: " + beratBadan + "\n");

        System.out.println(
            "========= Kumpulan Nilai =========");

        System.out.println(
            "Nilai Minimalnya double adalah: " + Double.MIN_VALUE);
        System.out.println(
            "Nilai Maksimalnya double adalah: " + Double.MAX_VALUE);

        System.out.println(
            "Nilai Minimalnya float adalah: " + Float.MIN_VALUE);
        System.out.println(
            "Nilai Maksimalnya float adalah: " + Float.MAX_VALUE);

        System.out.println(
            "==================================");
    }
}
