public class Day6 {
    public static void main(String[] args) {

        char jenisKelamin = 'P';
        boolean mahasiswa = true;

        System.out.println(
            "Nilai dari tipe data char adalah: " + jenisKelamin);
        System.out.println(
            "Nilai dari tipe data boolean adalah: " + mahasiswa + "\n");

        System.out.println(
            "========= Kumpulan Nilai =========");

        System.out.println(
            "Nilai Minimal char adalah: " + Character.MIN_VALUE);
        System.out.println(
            "Nilai Maksimal char adalah: " + Character.MAX_VALUE);

        System.out.println(
            "Nilai boolean true adalah: " + true);
        System.out.println(
            "Nilai boolean false adalah: " + false);

        System.out.println(
            "==================================");
    }
}
